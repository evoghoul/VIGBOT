def import_report() -> int:
    rows = [line.split("|") for line in REPORT.splitlines() if line.strip()]
    if len(rows) != 174 or len({row[1] for row in rows}) != 174:
        raise ValueError(f"Expected 174 unique report rows, found {len(rows)}")
    connection = sqlite3.connect(DB_PATH)
    try:
        for report_no, roll_no, name, year, section, cgpa, attendance, hosteler, gender, backlog_count in rows:
            values = (name, gender.upper(), int(year), float(cgpa), int(backlog_count), float(attendance), str(int(float(section))), 4, roll_no)
            if connection.execute("SELECT 1 FROM students WHERE roll_no = ?", (roll_no,)).fetchone():
                connection.execute("""UPDATE students SET full_name = ?, gender = ?, current_year_of_study = ?,
                    cgpa = ?, backlog_count = ?, overall_attendance_pct = ?, section_code = ?, semester = ?
                    WHERE roll_no = ?""", values)
            else:
                key = roll_no.lower()
                connection.execute("""INSERT INTO students
                    (student_id, user_id, roll_no, username, password_hash, full_name, gender, email,
                     programme_code, programme_name, department_code, batch_label, section_code,
                     current_year_of_study, cgpa, backlog_count, overall_attendance_pct,
                     fee_outstanding, status, semester)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                    (f"stu-{key}", f"usr-stu-{key}", roll_no, key, roll_no, name, gender.upper(),
                     f"{key}@vignan.ac.in", "BTCSE", "B.Tech Computer Science and Engineering",
                     "CSE", "2024-28 CSE", str(int(float(section))), int(year), float(cgpa),
                     int(backlog_count), float(attendance), 0.0, "ACTIVE", 4))
        connection.commit()
        return len(rows)
    finally:
        connection.close()


